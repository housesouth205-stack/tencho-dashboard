def build(*tables):
    d = {}
    for t in tables:
        for run, code in t.items():
            d[code] = run
    return d
WHITE = build(WHITE_T, WHITE_M, EXT_M)
BLACK = build(BLACK_T, BLACK_M, EXT_M)
MODES = {"1":"V0","011":"VR1","000011":"VR2","0000011":"VR3","010":"VL1","000010":"VL2",
         "0000010":"VL3","001":"H","0001":"P"}

class Bits:
    __slots__ = ("d", "i", "n")
    def __init__(self, data): self.d = data; self.i = 0; self.n = len(data) * 8
    def bit(self):
        if self.i >= self.n: raise EOFError
        b = (self.d[self.i >> 3] >> (7 - (self.i & 7))) & 1
        self.i += 1
        return b
    def eof(self): return self.i >= self.n

def read_run(bs, table):
    """MH符号を1つ読む。makeup(64以上)は terminating(0-63) が来るまで足していく。"""
    total = 0
    while True:
        code = ""
        while code not in table:
            code += str(bs.bit())
            if len(code) > 14: raise ValueError("bad run code " + code)
        run = table[code]
        total += run
        if run < 64: return total

def decode_g4(data, width, height):
    bs = Bits(data)
    ref = [width, width]
    rows = []
    for _ in range(height):
        cur = []
        a0 = -1
        color = 0
        try:
            while a0 < width:
                # b1: a0 より右で、a0 の色と反対の色の変化点
                i = 0
                while i < len(ref) and (ref[i] <= a0 or (i & 1) != color):
                    i += 1
                b1 = ref[i] if i < len(ref) else width
                b2 = ref[i + 1] if i + 1 < len(ref) else width
                code = ""
                mode = None
                while True:
                    code += str(bs.bit())
                    if code in MODES: mode = MODES[code]; break
                    if len(code) > 7:
                        if code.startswith("0000000"): raise EOFError
                        raise ValueError("bad mode " + code)
                if mode == "P":
                    a0 = b2
                elif mode == "H":
                    s = a0 if a0 > 0 else 0
                    r1 = read_run(bs, WHITE if color == 0 else BLACK)
                    r2 = read_run(bs, BLACK if color == 0 else WHITE)
                    a1 = min(s + r1, width); a2 = min(a1 + r2, width)
                    cur.append(a1); cur.append(a2)
                    a0 = a2
                else:
                    d = {"V0":0,"VR1":1,"VR2":2,"VR3":3,"VL1":-1,"VL2":-2,"VL3":-3}[mode]
                    a1 = min(max(b1 + d, 0), width)
                    cur.append(a1)
                    a0 = a1
                    color ^= 1
        except EOFError:
            rows.append(cur); break
        rows.append(cur)
        ref = cur + [width, width]
    # 変化点 → 1行ぶんのバイト列（1=黒）
    stride = (width + 7) // 8
    out = bytearray(stride * len(rows))
    for y, cur in enumerate(rows):
        base = y * stride
        color = 0; x = 0
        for t in cur + [width]:
            if color:
                for px in range(x, min(t, width)):
                    out[base + (px >> 3)] |= 0x80 >> (px & 7)
            x = t; color ^= 1
            if x >= width: break
    return bytes(out), len(rows)

def write_png(path, data, width, height, invert=True):
    """1bit グレースケールPNG。CCITTは1=黒なので、既定で反転して 0=黒 にする。"""
    stride = (width + 7) // 8
    raw = bytearray()
    for y in range(height):
        raw.append(0)
        row = data[y * stride:(y + 1) * stride]
        raw.extend(bytes(b ^ 0xFF for b in row) if invert else row)
    def chunk(tag, body):
        return struct.pack(">I", len(body)) + tag + body + struct.pack(">I", zlib.crc32(tag + body) & 0xffffffff)
    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 1, 0, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(bytes(raw), 6))
    png += chunk(b"IEND", b"")
    open(path, "wb").write(png)
